// Embeds the built SPA shell into the Worker bundle.
// Reads app/dist/index.html (single-file build: JS/CSS inlined, no separate
// assets) and writes src/shell.ts, which src/index.ts imports and serves on
// the museum's app routes. Run automatically by `npm run build`.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const distHtml = join(here, '..', 'dist', 'index.html')
const outTs = join(here, '..', '..', 'src', 'shell.ts')

const html = readFileSync(distHtml, 'utf8')
if (!html.includes('<div id="root">') || !html.includes('noindex')) {
  throw new Error('embed-shell: dist/index.html does not look like the museum shell; refusing to embed')
}

const ts =
  `// GENERATED by app/scripts/embed-shell.mjs — do not edit by hand.\n` +
  `// The built SPA shell (app/dist/index.html), served by the Worker on the\n` +
  `// museum's app routes. Regenerate with \`npm --prefix app run build\`.\n` +
  `export const SHELL_HTML = ${JSON.stringify(html)}\n`
writeFileSync(outTs, ts)
console.log(`embed-shell: wrote ${outTs} (${html.length} chars of shell)`)
